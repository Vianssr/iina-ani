import Foundation
@testable import IINA_ANI

@main enum XiFanRegression {
    enum Failure: Error { case assertion(String) }

    static func require(_ value: @autoclosure () -> Bool, _ message: String) throws {
        if !value() { throw Failure.assertion(message) }
    }

    static func page(_ ciphertext: String, uid: String = "abc123", code: Int = 200, type: String = "0") throws -> String {
        let data = try JSONSerialization.data(withJSONObject: [
            "code": code, "type": type, "config": ["uid": uid], "url": ciphertext
        ])
        return "<script>let ConFig = \(String(decoding: data, as: UTF8.self)), box = $('#player');</script>"
    }

    static func rejects(_ html: String, _ message: String) throws {
        do {
            _ = try XiFan.resolvedMedia(html)
        } catch { return }
        throw Failure.assertion(message)
    }

    static func main() throws {
        let script = #"MacPlayerConfig.player_list={"xfy2":{"parse":"https://player.moedot.net/player/index.php?code=xfdm1&url="}},MacPlayerConfig.downer_list={"http":{"parse":""}},MacPlayerConfig.server_list={"server1":{"parse":""}};"#
        let parsers = try XiFan.playerParsers(script)
        try require(parsers["http"] == nil && parsers["server1"] == nil,
                    "comma-chained download and server sections must not be parsed as playback routes")
        // Independent AES-CBC fixtures, not generated by the decoder under test.
        let first = "IschXXMw1jD70Vf1G7oFAUnJJ7/iqE+Gpsw6lz0Qyku/6hMUnfQpSuqD//HkB9XE4qS/8ggwoH63gA5roApNMw=="
        let media = try XiFan.resolvedMedia(page(first))
        try require(media == "https://media.example.invalid/episode%201.mp4?ticket=synthetic",
                    "the resolved media must retain percent encoding and its query, not the site's stale source URL")
        let second = "qM/XFW01iEu2yWkvTqd/X65xWPs7jc0QRi13plIbtW0rinmuw3qvuvRfd7Cyir8N"
        let secondMedia = try XiFan.resolvedMedia(page(second, uid: "def456"))
        try require(secondMedia == "https://media.example.invalid/second.m3u8",
                    "each response UID must derive its own decryption key")
        let automatic = try XiFan.resolvedMedia(page(second, uid: "def456", type: "auto"))
        try require(automatic == "https://media.example.invalid/second.m3u8",
                    "automatic type must decrypt and validate the original HLS URL, not reject current source responses")
        try rejects(page(first, code: 403), "an upstream error must never become a playable stream")
        try rejects(page("not-base64"), "a malformed encrypted payload must be rejected")
        try rejects(page("aylKftsVolVmb+z6FEPg6ynEbpcam0jbE1rdeozqGXla+H0poajdyAG2VVBxOey1"),
                    "decryption must not admit insecure media URLs")
        try rejects(page("7/JbwCtlaIz/LiEJlJJ1lQCNVb9DUn6Ex63MEqwAWCr0JNxxXJltuJ+UqEpDF6g04Yrdkied+Q2dg1D2oxNFyA=="),
                    "media URLs must not carry credentials")
        print("PASS XiFan resolved media, response-key binding, upstream errors and URL boundaries")
    }
}
